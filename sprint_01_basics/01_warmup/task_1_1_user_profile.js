'use strict';

/* ==============================================================================
   ЗАДАЧА 1.1: Генератор профиля пользователя
   
   🎯 ЦЕЛЬ:
   Написать функцию createUserCard(name, age, status), которая принимает данные
   о пользователе и склеивает их в красивую строку визитки:
    Пользователь: [name] Возраст: [age] Статус: [status]
   
   📥 ДЕФОЛТЫ (если передан null или undefined):
   • name   -> 'Аноним'
   • age    -> 18 (⚠️ ВАЖНО: возраст 0 должен остаться 0, используй ??)
   • status -> 'guest'
============================================================================== */

function createUserCard(name, age, status) {
  const finalName = name ?? 'Аноним'
  const finalAge = age ?? 18
  const finalStatus = status ?? 'guest'

  return `Пользователь: ${finalName}, Возраст: ${finalAge}, Статус: ${finalStatus}`;
}

// ==============================================================================
// 🧪 ПРИМЕРЫ ВЫЗОВА И ТЕСТЫ:
// ==============================================================================
 console.log(createUserCard('Иван', 25, 'admin')); // Пользователь: Иван Возраст: 25 Статус: admin
 console.log(createUserCard('Малыш', 0, 'vip'));    // Пользователь: Малыш Возраст: 0 Статус: vip
 console.log(createUserCard(null, null, null));    // Пользователь: Аноним Возраст: 18 Статус: guest
 console.log(createUserCard());                    // Пользователь: Аноним Возраст: 18 Статус: guest
