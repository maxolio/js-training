'use strict'

/* ==============================================================================
   ЗАДАЧА 6.1: Оценка рейтинга и действия через switch (Урок 06)

   🎯 ЧАСТЬ 1: Функция getGradeInfo(score)
   Принимает балл `score` (число) и возвращает строку с оценкой:
   • 90 .. 100 ➔ "Отлично (A)"
   • 75 .. 89  ➔ "Хорошо (B)"
   • 60 .. 74  ➔ "Удовлетворительно (C)"
   • 0  .. 59  ➔ "Неудовлетворительно (F)"
   • Любое другое значение (например, < 0 или > 100) ➔ "Некорректный балл"
   ⚠️ ТРЕБОВАНИЕ: Использовать конструкцию switch (true) и return!

   🎯 ЧАСТЬ 2: Функция handleUserAction(actionCode)
   Принимает код действия `actionCode` (число или строку) со СТРОГОЙ проверкой типов:
   • 1 или "create" ➔ "Создание записи"
   • 2 или "edit"   ➔ "Редактирование записи"
   • 3 или "delete" ➔ "Удаление записи"
   • Любое другое   ➔ "Действие не распознано"
   ⚠️ ТРЕБОВАНИЕ: Использовать классический switch (actionCode) с группировкой кейсов и return!
============================================================================== */

// НАПИШИ СВОЙ КОД ЗДЕСЬ:

function getGradeInfo(score) {
  switch (true) {
    case score >= 90 && score <= 100:
      return 'Отлично (А)'

    case score >= 75 && score < 90:
      return 'Хорошо (Б)'

    case score >= 60 && score < 75:
      return 'Удовлетворительно (С)'

    case score >= 0 && score < 60:
      return 'Неудовлетворительно (F)'

    default:
      return 'Некорректный балл'
  }
}

function handleUserAction(actionCode) {
  switch (actionCode) {
    case 1:
    case 'create':  // Группировка: сработает и на число 1, и на строку 'create'
      return 'Создание записи'

    case 2:
    case 'edit':
      return 'Редактирование записи'

    case 3:
    case 'delete':
      return 'Удаление записи'

    default:
      return 'Действие не распознано'
  }
}

// ==============================================================================
// 🧪 ПРИМЕРЫ ВЫЗОВА И ТЕСТЫ:
// ==============================================================================
console.log(getGradeInfo(95))  // "Отлично (A)"
console.log(getGradeInfo(75))  // "Хорошо (B)"
console.log(getGradeInfo(50))  // "Неудовлетворительно (F)"
console.log(getGradeInfo(-5))  // "Некорректный балл"

console.log(handleUserAction(1))        // "Создание записи" (число 1)
console.log(handleUserAction('create')) // "Создание записи" (строка "create")
console.log(handleUserAction('1'))      // "Действие не распознано" (строка "1" !== числу 1)
console.log(handleUserAction('unknown'))// "Действие не распознано"