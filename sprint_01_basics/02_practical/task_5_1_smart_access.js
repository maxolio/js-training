// НАПИШИ СВОЕ РЕШЕНИЕ ЗДЕСЬ:
function checkAccess(age, hasTicket, isVip, balance) {
  const userBalance = balance ?? 100

  const isAllowed = (age >= 18 && hasTicket) || Boolean(isVip)

  return isAllowed
    ? (userBalance >= 50 ? 'Полный доступ' : 'Ограниченный доступ')
    : 'Доступ запрещен'
}

