/* ==============================================================================
   ЗАДАЧА 7.1: Генератор четных чисел с лимитом (Урок 07)

   🎯 ЦЕЛЬ:
   Написать функцию generateSequence(limit, maxItems), которая находит четные
   числа в диапазоне от 1 до limit и возвращает их строкой через пробел.

   📋 ТРЕБОВАНИЯ:
   1. Запусти цикл for от 1 до limit включительно (let i = 1; i <= limit; i++).
   2. Заведи счетчик найденных четных чисел `foundCount = 0` и строку `result = ''`.
   3. Если число НЕЧЕТНОЕ (i % 2 !== 0) ➔ пропусти его через оператор `continue`.
   4. Если число четное:
      • Добавь его в строку `result` (с пробелом).
      • Увеличь `foundCount++`.
   5. Если количество найденных чисел достигло `maxItems` (foundCount === maxItems) ➔
      немедленно останови цикл через оператор `break`.
   6. Верни очищенную от лишних пробелов строку (метод .trim()).
============================================================================== */

// НАПИШИ СВОЕ РЕШЕНИЕ ЗДЕСЬ:
function generateSequence(limit, maxItems) {
  let result = ''
  let foundCount = 0

  for (let i = 1; i <= limit; i++) {
    if (i % 2 !== 0) {
      continue
    }

    result += `${i} `
    foundCount++

    if (foundCount === maxItems) {
      break
    }
  }

  return result.trim()
}

// ==============================================================================
// 🧪 ПРИМЕРЫ ВЫЗОВА И ТЕСТЫ:
// ==============================================================================
console.log(generateSequence(20, 4)) // "2 4 6 8" (нашли 4 числа и остановились по break)
console.log(generateSequence(7, 10)) // "2 4 6" (дошли до limit=7 раньше, чем набрали 10)
console.log(generateSequence(1, 5))  // "" (четных чисел нет)

/* ==============================================================================
   ЗАДАЧА 7.2: Безопасный ввод пароля через do...while (Урок 07)

   🎯 ЦЕЛЬ:
   Написать функцию loginSystem(maxAttempts), которая эмулирует авторизацию
   пользователя с ограничением количества попыток.

   📋 ТРЕБОВАНИЯ:
   1. Объяви правильный пароль константой: `const CORRECT_PASSWORD = 'admin123';`.
   2. Используй цикл `do...while`:
      • Запроси пароль через `prompt('Введите пароль:')`.
      • Уменьшай счетчик оставшихся попыток `maxAttempts--`.
      • Если введенный пароль совпал с правильным ➔ немедленно верни:
        "Доступ разрешен! 🔓"
   3. Условие продолжения цикла `while (maxAttempts > 0)`.
   4. Если цикл завершился (попытки исчерпаны, а пароль так и не угадан) ➔ верни:
      "Аккаунт заблокирован! 🔒"
============================================================================== */

// НАПИШИ СВОЕ РЕШЕНИЕ ЗДЕСЬ:
function loginSystem(maxAttempts) {
  const CORRECT_PASSWORD = 'admin123'
  let enteredPassword

  do {
    enteredPassword = prompt(`Введите пароль (осталось попыток: ${maxAttempts}):`)
    maxAttempts--

    // Если пароль подошел — сразу возвращаем успех и завершаем функцию
    if (enteredPassword === CORRECT_PASSWORD) {
      return 'Доступ разрешен! 🔓'
    }

    // Крутим цикл, пока есть попытки
  } while (maxAttempts > 0)

  // Если все попытки потрачены, а верный пароль не был введен
  return 'Аккаунт заблокирован! 🔒'
}

